// ============================================================
// Ref — 响应式引用，对标 Vue 的 ref()
// ============================================================

export interface Ref<T = any> {
  value: T
}

/**
 * 创建一个响应式引用
 *
 * @example
 * const count = ref(0)
 * count.value // => 0
 * count.value++ // 触发更新
 */
export function ref<T>(value: T): Ref<T> {
  return {
    value,
  }
}
